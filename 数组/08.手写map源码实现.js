/**
 * ==============================================================================
 * 工业级 Array.prototype.map 完整手写实现（严格对齐 ECMAScript 官方规范）
 * ==============================================================================
 */

Array.prototype.myMap = function(callbackFn, thisArg) {
  // ----------------------------------------------------------------------------
  // 第一步：防御性检查（调用者不能为 null 或 undefined）
  // ----------------------------------------------------------------------------
  if (this == null) {
    throw new TypeError('Cannot read property "myMap" of ' + this);
  }

  // ----------------------------------------------------------------------------
  // 第二步：回调函数检查
  // ----------------------------------------------------------------------------
  if (typeof callbackFn !== 'function') {
    throw new TypeError(callbackFn + ' is not a function');
  }

  // ----------------------------------------------------------------------------
  // 第三步：强制转为对象（为了支持类数组、字符串等通用场景）
  // ----------------------------------------------------------------------------
  const O = Object(this);

  // ----------------------------------------------------------------------------
  // 第四步：无符号右移运算 (ToLength 规范)
  // 作用：如果 length 是负数、NaN 或非数字，自动转为合法正整数 (0 到 2^32 - 1)
  // ----------------------------------------------------------------------------
  const len = O.length >>> 0;

  // ----------------------------------------------------------------------------
  // 第五步：创建一个同等长度的新数组，绝不污染原数组
  // ----------------------------------------------------------------------------
  const A = new Array(len);

  // ----------------------------------------------------------------------------
  // 第六步：核心遍历循环（使用 while / for 遍历）
  // ----------------------------------------------------------------------------
  let k = 0;
  while (k < len) {
    // 关键细节：用 in 操作符检查当前下标 k 是否真实存在！
    // 目的：主动跳过“稀疏数组（Sparse Array）”的空洞（Holes），空洞处不调用回调！
    if (k in O) {
      const kValue = O[k]; // 当前项

      // 核心调用：使用 call 绑定 thisArg，并严格灌入 3 个规范参数：(当前项, 下标, 原数组)
      const mappedValue = callbackFn.call(thisArg, kValue, k, O);

      // 把加工后的结果写入新数组对应位置
      A[k] = mappedValue;
    }
    k++;
  }

  // ----------------------------------------------------------------------------
  // 第七步：返回全新数组
  // ----------------------------------------------------------------------------
  return A;
};


// ==============================================================================
// 验证与测试用例（直接在终端运行看结果）
// ==============================================================================

// 1. 基础转换测试
const nums = [1, 2, 3];
const doubled = nums.myMap(x => x * 10);
console.log("【测试 1 基础转换】:", doubled); // [10, 20, 30]
console.log("【原数组不受影响】:", nums);    // [1, 2, 3]

// 2. 传参验证：亲眼看一下传出来的 3 个参数
nums.myMap((item, index, array) => {
  console.log(`【测试 2 传参】第 ${index} 项是: ${item}`);
});

// 3. 空洞（稀疏数组）跳过测试
const sparseArr = new Array(3); // 里面全为空洞
const sparseRes = sparseArr.myMap(x => 'A');
console.log("【测试 3 空洞跳过】:", sparseRes); // [ <3 empty items> ]（回调一次都没执行！）

// 4. thisArg 绑定测试
const multiplier = {
  factor: 5,
  multiply(val) {
    return val * this.factor;
  }
};
const multiplied = [1, 2, 3].myMap(function(val) {
  return this.multiply(val);
}, multiplier); // 传入 multiplier 改变 this 指向
console.log("【测试 4 thisArg 绑定】:", multiplied); // [5, 10, 15]
